// generate-seo-shell.mjs — post-build SEO step (runs right after `vite build`).
//
// 1. Prerenders the HOMEPAGE into dist/index.html:
//    a. injects the STATIC HERO REPLICA (announcement bar + hero stage,
//       generated from the real components by scripts/generate-hero-replica.tsx)
//       into <div id="hero-root">, placed right before #root. The replica
//       paints the LCP element at FCP; React hydrates it via the bridge
//       (src/heroBridge.tsx) so the node is ADOPTED, never re-created.
//    b. injects the storefront H1, description and real category links
//       inside <div id="root"> (crawlers / no-JS see real content; React's
//       createRoot().render() replaces the injected block on mount).
//    c. injects window.__PB_ANNOUNCEMENT__ (build-time CMS snapshot) so the
//       bridge's first client render matches the replica byte-for-byte.
// 2. Emits api/_lib/seoShell.generated.ts with TWO shells:
//    - SEO_SHELL_HTML: shell with #hero-root EMPTY (product / category /
//      services pages — no hero there; the runtime prerender replaces the
//      #root content for those pages).
//    - SEO_HOME_SHELL_HTML: full homepage shell (hero replica + #root block)
//      used by the runtime homepage renderer.
//
// Escaping: HTML embedded in a TS template literal — backticks, backslashes
// and ${ are escaped. `</script>` inside the HTML is safe (JS module context).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distIndex = path.join(root, "dist", "index.html");
const outFile = path.join(root, "api", "_lib", "seoShell.generated.ts");
const replicaJsonPath = path.join(root, "api", "_lib", "heroReplica.generated.json");

// Build-time CMS announcement (legacy hand-written fallback value; the
// generated replica carries the same text — see generate-hero-replica.tsx).
const ANNOUNCEMENT_TEXT =
  "🔥 Global Best Prices 🌍 | ⚡ Instant Delivery 🚀 | 🔒 Secure Payments 💳 | 🌎 Available Worldwide ✨ | 💎 Trusted Premium Products⭐";

function fallbackModule(comment) {
  writeFileSync(
    outFile,
    "// AUTO-GENERATED by scripts/generate-seo-shell.mjs — do not edit.\n" +
      `// (${comment})\n` +
      'export const SEO_SHELL_HTML = "";\n' +
      'export const SEO_HOME_SHELL_HTML = "";\n'
  );
  process.exit(0);
}

// ---- static hero replica ------------------------------------------------
// Preferred: the component-rendered replica (byte-identical to what the
// client hydrates). Fallback: the legacy simplified hero block (LCP still
// early, but React re-creates the interactive hero at commit — the previous
// behavior).
let replicaHtml = null;
let announcementSnapshot = null;
if (existsSync(replicaJsonPath)) {
  try {
    const j = JSON.parse(readFileSync(replicaJsonPath, "utf8"));
    if (typeof j.html === "string" && j.html.includes("pbhs-stage")) {
      replicaHtml = j.html;
      announcementSnapshot = j.announcement || null;
    }
  } catch {
    /* fall back below */
  }
}

const LEGACY_HERO_REPLICA =
  '<div class="pbhs-scroll relative w-full overflow-x-auto bg-[#000b1d] [scrollbar-width:none]"><main class="pbhs-stage relative" style="background-image:url(/hero_header_v3.webp)"></main></div>';

const HOMEPAGE_BLOCK = (withAnnouncement) => `
      <!-- Perf (task §5/§10): transitional SEO content inside #root. Replaced
           by the React app on mount (createRoot). The announcement bar + hero
           stage live OUTSIDE #root in #hero-root (hydrated/adopted by the
           bridge) so the LCP element is never destroyed and re-created. -->
      ${withAnnouncement ? `<div class="w-full bg-gradient-to-r from-amber-400/15 via-[#0A122E] to-amber-400/15 border-b border-amber-400/25 text-center py-2 px-4"><span class="text-[11px] sm:text-xs font-semibold text-amber-300 font-mono">${ANNOUNCEMENT_TEXT}</span></div>` : ""}
      <!-- system-ui only (NO webfont) on the transitional block: with Inter,
           the slow-network font swap reflowed this in-viewport text and
           Lighthouse measured it as CLS. This block is replaced by the React
           app within ~1s, so the transitional typeface is imperceptible. -->
      <div style="min-height:100vh;background:#050814;color:#e5e7eb;font-family:system-ui,-apple-system,Segoe UI,sans-serif;padding:24px 16px;box-sizing:border-box"><div style="max-width:920px;margin:0 auto">
      <h1 style="color:#fff;font-size:26px;line-height:1.25;margin:10px 0 14px;font-weight:800">Premium Digital Marketplace &amp; Smart Projectors</h1>
      <p style="line-height:1.7;color:#c7ccd6;margin:0 0 14px;font-size:15px">Instant digital keys, gaming accounts, subscriptions, AI tools, SaaS licenses, and high-performance 4K Smart Projectors with 24/7 automated delivery.</p>
      <h2 style="color:#fff;font-size:18px;margin:6px 0 10px;font-weight:700">Browse by category</h2>
      <ul style="list-style:disc;padding-left:20px;margin:0 0 14px;color:#c7ccd6">
        <li><a href="/streaming" style="color:#7dd3fc">Streaming</a></li>
        <li><a href="/subscriptions" style="color:#7dd3fc">Subscriptions</a></li>
        <li><a href="/gift-cards" style="color:#7dd3fc">Gift Cards</a></li>
        <li><a href="/gaming" style="color:#7dd3fc">Gaming</a></li>
        <li><a href="/software" style="color:#7dd3fc">Software</a></li>
        <li><a href="/smart-projectors" style="color:#7dd3fc">Smart Projectors</a></li>
        <li><a href="/smart-4k-projectors" style="color:#7dd3fc">Smart 4K Projectors</a></li>
        <li><a href="/ai-subscriptions" style="color:#7dd3fc">AI Subscriptions</a></li>
        <li><a href="/steam-game-keys" style="color:#7dd3fc">Steam &amp; Game Keys</a></li>
        <li><a href="/windows-office" style="color:#7dd3fc">Windows &amp; Office</a></li>
        <li><a href="/creative-software" style="color:#7dd3fc">Creative Software</a></li>
        <li><a href="/digital-services" style="color:#7dd3fc">Digital Services</a></li>
        <li><a href="/social-media" style="color:#7dd3fc">Social Media</a></li>
        <li><a href="/web-hosting" style="color:#7dd3fc">Web Hosting</a></li>
        <li><a href="/digital-marketing" style="color:#7dd3fc">Digital Marketing</a></li>
        <li><a href="/web3" style="color:#7dd3fc">Web3</a></li>
      </ul>
      </div></div>`;

if (!existsSync(distIndex)) {
  console.warn("[generate-seo-shell] dist/index.html not found — emitting fallback module");
  fallbackModule("fallback: dist/index.html was missing at build time");
}

let html = readFileSync(distIndex, "utf8");
if (!html.includes('<div id="root"')) {
  console.warn("[generate-seo-shell] dist/index.html has no #root — emitting fallback module");
  fallbackModule("fallback: no #root in dist/index.html");
}

// ---- 0) announcement snapshot script (hydration parity for the bridge) ----
const snapshotScript = announcementSnapshot
  ? `<script>window.__PB_ANNOUNCEMENT__=${JSON.stringify(announcementSnapshot)};</script>`
  : "";

if (snapshotScript && html.includes("</head>")) {
  html = html.replace("</head>", `    ${snapshotScript}\n  </head>`);
}

// ---- 1) prerender the homepage into the static file ----
// hero-root: filled with the replica (or the legacy block as fallback)
const heroRootMarker = '<div id="hero-root"></div>';
const heroContent = replicaHtml ?? LEGACY_HERO_REPLICA;
if (html.includes(heroRootMarker)) {
  html = html.replace(heroRootMarker, `<div id="hero-root">${heroContent}</div>`);
} else {
  // Older template without the container — inject it before #root
  html = html.replace(
    /(<div id="root")/,
    `<div id="hero-root">${heroContent}</div>\n    $1`
  );
}

// #root: transitional SEO content. When the component-rendered replica owns
// the announcement bar, do NOT duplicate it inside #root (the legacy
// hand-written replica has no announcement, so the block keeps carrying it).
const homepageBlock = HOMEPAGE_BLOCK(replicaHtml == null);
const rootMarker = '<div id="root"></div>';
if (html.includes(rootMarker)) {
  html = html.replace(rootMarker, `<div id="root">${homepageBlock}</div>`);
  writeFileSync(distIndex, html);
  console.log(
    `[generate-seo-shell] homepage prerendered into dist/index.html (+${replicaHtml ? "component-rendered" : "legacy"} hero replica in #hero-root)`
  );
} else {
  console.warn("[generate-seo-shell] #root not empty-placeholder — homepage prerender skipped");
}

// ---- 2) emit the shell module for the runtime prerender layer ----
// Variant A: non-home pages — #hero-root emptied (no hero there), the
// homepage #root block stays (the runtime injectors replace it).
const shellForOtherPages = html.replace(
  /<div id="hero-root">[\s\S]*?<\/div>(?=\s*<div id="root")/,
  '<div id="hero-root"></div>'
);
// Variant B: full homepage shell (hero replica + #root block).

// escape for embedding inside a TS template literal: backslashes first, then
// backticks, then ${
function toTsTemplate(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const out =
  "// AUTO-GENERATED by scripts/generate-seo-shell.mjs — do not edit.\n" +
  "// Source: dist/index.html (built SPA shell). Regenerated on every build.\n" +
  "// SEO_SHELL_HTML: #hero-root emptied — base shell for product/category/\n" +
  "//   services/static pages (runtime prerender replaces the #root content).\n" +
  "// SEO_HOME_SHELL_HTML: full homepage shell incl. the static hero replica.\n" +
  "export const SEO_SHELL_HTML = `" + toTsTemplate(shellForOtherPages) + "`;\n" +
  "export const SEO_HOME_SHELL_HTML = `" + toTsTemplate(html) + "`;\n";

writeFileSync(outFile, out);
console.log(`[generate-seo-shell] wrote api/_lib/seoShell.generated.ts (${(out.length / 1024).toFixed(1)} KB)`);
