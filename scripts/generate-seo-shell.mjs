// generate-seo-shell.mjs — build step run immediately after `vite build`.
//
// Reads dist/index.html (the BUILT SPA shell with hashed asset URLs) and
// emits api/_lib/seoShell.generated.ts so the serverless prerender layer
// (api/_lib/prerender.ts) can serve real per-page HTML from the same shell
// the browser loads. The generated module is committed: the /api/products
// function imports it statically, so the deploy bundle always carries it.
//
// Escaping: the HTML is embedded in a TS template literal — backticks,
// backslashes and ${ are escaped. `</script>` inside the HTML is safe here
// (this is a JS module, not an inline <script> block).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distIndex = path.join(root, "dist", "index.html");
const outFile = path.join(root, "api", "_lib", "seoShell.generated.ts");

if (!existsSync(distIndex)) {
  // Never fail the deploy on a missing dist (e.g. API-only rebuilds) — emit a
  // placeholder that makes the prerender layer fall back to its minimal shell.
  console.warn("[generate-seo-shell] dist/index.html not found — emitting fallback module");
  writeFileSync(
    outFile,
    "// AUTO-GENERATED by scripts/generate-seo-shell.mjs — do not edit.\n" +
      "// (fallback: dist/index.html was missing at build time)\n" +
      'export const SEO_SHELL_HTML = "";\n'
  );
  process.exit(0);
}

const html = readFileSync(distIndex, "utf8");
if (!html.includes('<div id="root"')) {
  console.warn("[generate-seo-shell] dist/index.html has no #root — emitting fallback module");
  writeFileSync(
    outFile,
    "// AUTO-GENERATED by scripts/generate-seo-shell.mjs — do not edit.\n" +
      'export const SEO_SHELL_HTML = "";\n'
  );
  process.exit(0);
}

const escaped = html.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const out =
  "// AUTO-GENERATED by scripts/generate-seo-shell.mjs — do not edit.\n" +
  "// Source: dist/index.html (built SPA shell). Regenerated on every build.\n" +
  "export const SEO_SHELL_HTML = `" + escaped + "`;\n";

writeFileSync(outFile, out);
console.log(
  `[generate-seo-shell] wrote api/_lib/seoShell.generated.ts (${(out.length / 1024).toFixed(1)} KB)`
);
